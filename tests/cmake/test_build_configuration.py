"""Validate the generated compiler commands for the core-only LTO policy."""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import sysconfig
from pathlib import Path

import pytest


@pytest.mark.skipif(
    sys.platform != "linux" or shutil.which("cmake") is None,
    reason="Compile-command checks run on Linux with CMake installed",
)
def test_core_lto(tmp_path: Path) -> None:
    root = Path(__file__).resolve().parents[2]

    def configure(enabled: bool) -> str:
        result = subprocess.run(
            [
                "cmake",
                "-S",
                str(root),
                "-B",
                str(tmp_path),
                "-DCMAKE_BUILD_TYPE=Release",
                "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON",
                "-DSYMUSIC_BUILD_PYTHON=ON",
                f"-DSYMUSIC_ENABLE_LTO={'ON' if enabled else 'OFF'}",
                f"-DPython_EXECUTABLE={sys.executable}",
            ],
            check=True,
            capture_output=True,
            text=True,
        )
        return result.stdout + result.stderr

    output = configure(True)
    if "Core LTO is unavailable" in output:
        pytest.skip("The host compiler cannot link LTO objects")

    def commands_for(directory: Path) -> list[str]:
        entries = json.loads((tmp_path / "compile_commands.json").read_text())
        return [
            entry["command"]
            for entry in entries
            if Path(entry["file"]).is_relative_to(directory)
        ]

    core = commands_for(root / "src")
    binding = commands_for(root / "py_src")
    nanobind = commands_for(root / "3rdparty" / "nanobind" / "src")
    assert core
    assert binding
    assert nanobind
    assert all("-flto" in command for command in core)
    assert all("-flto" not in command for command in binding + nanobind)

    configure(False)
    assert all("-flto" not in command for command in commands_for(root / "src"))


@pytest.mark.skipif(shutil.which("cmake") is None, reason="Configure checks need CMake")
def test_deprecated_option_alias(tmp_path: Path) -> None:
    root = Path(__file__).resolve().parents[2]
    result = subprocess.run(
        ["cmake", "-S", str(root), "-B", str(tmp_path), "-DBUILD_SYMUSIC_TEST=ON"],
        check=True,
        capture_output=True,
        text=True,
    )
    assert "BUILD_SYMUSIC_TEST is deprecated" in result.stderr
    cache = (tmp_path / "CMakeCache.txt").read_text()
    assert "SYMUSIC_BUILD_TESTS:BOOL=ON" in cache


@pytest.mark.skipif(
    sys.platform != "linux" or shutil.which("cmake") is None,
    reason="Compile-command checks run on Linux with CMake installed",
)
def test_cross_stub(tmp_path: Path) -> None:
    root = Path(__file__).resolve().parents[2]
    command = [
        "cmake",
        "-S",
        str(root),
        "-B",
        str(tmp_path / "build"),
        "-DCMAKE_SYSTEM_NAME=Linux",
        "-DSYMUSIC_BUILD_PYTHON=ON",
        "-DSYMUSIC_FAST_BUILD=ON",
        f"-DPython_EXECUTABLE={sys.executable}",
        f"-DPython_INCLUDE_DIR={sysconfig.get_path('include')}",
    ]
    result = subprocess.run(command, capture_output=True, text=True)
    assert result.returncode != 0
    assert "Cross builds require SYMUSIC_PYTHON_STUB" in result.stderr

    stub = tmp_path / "core.pyi"
    stub.write_text("# Generated by the native build.\n")
    result = subprocess.run(
        [*command, f"-DSYMUSIC_PYTHON_STUB={stub}"],
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stdout + result.stderr


@pytest.mark.skipif(
    sys.platform != "linux" or shutil.which("cmake") is None,
    reason="Compile-command checks run on Linux with CMake installed",
)
def test_sanitize_option(tmp_path: Path) -> None:
    root = Path(__file__).resolve().parents[2]

    def commands(*options: str) -> list[str]:
        subprocess.run(
            [
                "cmake",
                "-S",
                str(root),
                "-B",
                str(tmp_path),
                "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON",
                *options,
            ],
            check=True,
            capture_output=True,
            text=True,
        )
        entries = json.loads((tmp_path / "compile_commands.json").read_text())
        return [
            entry["command"]
            for entry in entries
            if Path(entry["file"]).is_relative_to(root / "src")
        ]

    plain = commands("-DSYMUSIC_SANITIZE=")
    assert plain
    assert all("-fsanitize" not in command for command in plain)

    sanitized = commands("-DSYMUSIC_SANITIZE=address;undefined")
    assert all("-fsanitize=address,undefined" in command for command in sanitized)
    assert all("-fno-omit-frame-pointer" in command for command in sanitized)
    assert all("-fno-sanitize-recover=undefined" in command for command in sanitized)
